/* ============================================================
 * core/rng.js —— 确定性随机（编辑器本地）
 * ------------------------------------------------------------
 * 只用于「自动弯曲」道路的曲线抖动（`map/map-render.js` 的 `curvePath`）。
 * 为什么不用引擎的 `HL.Rng`：
 *   · 两者的序列不同 —— 换掉会改变所有已有地图的弯曲观感，属于无收益的
 *     表现回归；
 *   · 引擎的 `Rng` 服务于世界生成（噪声 / 地形比例），与本文件不是同一职责；
 *   · 客户端 `map/road-curves.js` 另有自己的 `mulberry32`，三方本就各自独立。
 * 因此这里保留编辑器自己的一份，并对它封闭（只有曲线渲染使用）。
 * ============================================================ */
(function (E) {
  'use strict';

  /** 由字符串 key 得到确定性随机数发生器 */
  E.seeded = function (key) {
    let h = 0;
    for (const ch of key) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
    h = (h + 7) >>> 0;
    return function () {
      h |= 0;
      h = h + 0x6D2B79F5 | 0;
      let t = Math.imul(h ^ h >>> 15, 1 | h);
      t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t;
      return ((t ^ t >>> 14) >>> 0) / 4294967296;
    };
  };
})(window.MapEditor = window.MapEditor || {});
